#![allow(static_mut_refs)]

// Single-threaded wasm state; all access stays on the CPU worker.
//
// Debug-only block map of the module being generated: for every basic block, its guest
// address range and the byte range its code occupies in the module's function body.
//
// What it is for: static Wasm-op density per guest instruction is an average over every arm
// of a module, cold slow paths included. Joined with per-block execution counts (trace2,
// keyed by the same physical block address), it becomes EXECUTED density:
// sum(exec * ops_block) / sum(exec * instructions_block).
//
// Observation only. Recording reads `instruction_body_length()` between work items; it emits
// nothing, so the generated bytes are identical with the map on or off, and the switch is
// deliberately NOT part of the codegen fingerprint. Default OFF; when off every hook is one
// predictable branch.
//
// Ranges: a block's range runs from where the emitter starts its work item to where the next
// work item starts, so it covers the block body AND its terminator (branch, chain/exit code).
// Code that belongs to no block (dispatcher, loop/block structure, the module epilogue) is
// outside every range. Offsets are relative to the first instruction of the function body,
// i.e. right after the locals declaration; `body_length` excludes the final `end`.
//
// Lifetime: the map describes the LAST module generated. jit_generate_module may run more
// than once per compile (guard-group dry run), but the final run is the one finalized, and
// codegen_finalize hands its bytes to JS synchronously — read the map there.
//
// Layout: generated code embeds absolute addresses of engine statics, so any new data moves
// some of those constants in every module (as any engine change that adds a static does; the
// AOT cache is keyed on the engine binary's hash for that reason). To keep the move minimal the
// state is one small all-zero static (.bss) and the code never indexes (no panic location
// rodata). With the same engine binary the bytes are identical with the map on or off.

use crate::jit::BasicBlock;
use crate::page::Page;
use crate::trace_profiler;

pub const FLAG_ENTRY: u32 = 1;
/// The block's page was watched by trace2 at compile time, so its code carries the exec
/// counter (and, for indirect terminals, the target recorder): its op count is inflated by
/// the instrument.
pub const FLAG_TRACED: u32 = 2;

/// Record layout read by JS straight from linear memory: 8 x u32, little endian.
#[derive(Clone, Copy)]
#[repr(C)]
pub struct BlockMapEntry {
    pub addr: u32,
    pub virt_addr: u32,
    pub end_addr: u32,
    pub last_instruction_addr: u32,
    pub instructions: u32,
    pub body_start: u32,
    pub body_end: u32,
    pub flags: u32,
}

struct State {
    enabled: bool,
    /// The last entry is still open (its body_end is not known yet).
    open: bool,
    complete: bool,
    body_length: u32,
    /// None (all-zero) until the first block, so the static stays in .bss.
    blocks: Option<Vec<BlockMapEntry>>,
}

static mut STATE: State = State {
    enabled: false,
    open: false,
    complete: false,
    body_length: 0,
    blocks: None,
};

#[inline]
fn state() -> &'static mut State { unsafe { &mut *std::ptr::addr_of_mut!(STATE) } }

#[inline]
fn enabled() -> bool { state().enabled }

fn reset(s: &mut State) {
    if let Some(v) = s.blocks.as_mut() {
        v.clear();
    }
    s.open = false;
    s.complete = false;
    s.body_length = 0;
}

fn close(s: &mut State, body_offset: u32) {
    if s.open {
        if let Some(last) = s.blocks.as_mut().and_then(|v| v.last_mut()) {
            last.body_end = body_offset;
        }
        s.open = false;
    }
}

/// The state while recording, else None.
#[inline]
fn recording() -> Option<&'static mut State> { Some(state()).filter(|s| s.enabled) }

/// Start of jit_generate_module (after the builder reset).
pub fn begin_module() {
    if let Some(s) = recording() {
        reset(s);
    }
}

/// A work item starts at `body_offset`: closes the open block, opens `block` if any.
pub fn mark(body_offset: u32, block: Option<&BasicBlock>) {
    let Some(s) = recording() else { return };
    close(s, body_offset);
    if let Some(b) = block {
        let mut flags = 0;
        if b.is_entry_block {
            flags |= FLAG_ENTRY;
        }
        if trace_profiler::is_page_watched(Page::page_of(b.addr)) {
            flags |= FLAG_TRACED;
        }
        s.blocks.get_or_insert_with(Vec::new).push(BlockMapEntry {
            addr: b.addr,
            virt_addr: b.virt_addr as u32,
            end_addr: b.end_addr,
            last_instruction_addr: b.last_instruction_addr,
            instructions: b.number_of_instructions,
            body_start: body_offset,
            body_end: body_offset,
            flags,
        });
        s.open = true;
    }
}

/// Just before the builder finishes the module; `body_length` is the instruction body size.
pub fn end_module(body_length: u32) {
    let Some(s) = recording() else { return };
    close(s, body_length);
    s.body_length = body_length;
    s.complete = true;
}

#[no_mangle]
pub unsafe fn jit_block_map_set_enabled(on: u32) {
    let s = state();
    s.enabled = on != 0;
    reset(s);
}

#[no_mangle]
pub unsafe fn jit_block_map_enabled() -> u32 { enabled() as u32 }

/// Entries of the last completed module; 0 while off or before any module completed.
#[no_mangle]
pub unsafe fn jit_block_map_count() -> u32 {
    recording()
        .filter(|s| s.complete)
        .and_then(|s| s.blocks.as_ref())
        .map_or(0, |v| v.len() as u32)
}

/// Linear-memory address of entry 0 (stride 32 bytes, see BlockMapEntry).
#[no_mangle]
pub unsafe fn jit_block_map_ptr() -> u32 { state().blocks.as_ref().map_or(0, |v| v.as_ptr() as u32) }

/// Instruction body length of the mapped module (the final `end` excluded) — the consumer's
/// check that the map belongs to the bytes it holds.
#[no_mangle]
pub unsafe fn jit_block_map_body_length() -> u32 { state().body_length }
